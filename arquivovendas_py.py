produtos = []
vendas = []


def cadastrar_produto():
    nome = input("Digite o nome do produto: ")

    try:
        preco = float(input("Digite o preço do produto: "))
        quantidade = int(input("Digite a quantidade desse produto: "))

    except ValueError:
        print("Entrada inválida! Digite números válidos.")
        return

    if preco < 0 or quantidade < 0:
        print("Valores inválidos")
        return

    organizar_produto = {
        "nome": nome,
        "preco": preco,
        "quantidade": quantidade
    }

    produtos.append(organizar_produto)
    print("Cadastro realizado!")


def listar_produtos():
    if len(produtos) == 0:
        print("Nenhum produto cadastrado.")
    else:
        for i in produtos:
            print(f"Nome: {i['nome']}")
            print(f"Preço: R$ {i['preco']:.2f}")
            print(f"Quantidade: {i['quantidade']}")


def realizar_venda():
    print("Qual produto deseja comprar:")
    produto_comprado = input()

    print("Quantas unidades deseja comprar:")

    try:
        quantidade_produto = int(input())

    except ValueError:
        print("Quantidade inválida!")
        return

    produto_encontrado = False

    for i in produtos:
        if produto_comprado == i["nome"]:
            produto_encontrado = True

            if quantidade_produto <= 0:
                print("Quantidade inválida!")

            elif quantidade_produto <= i["quantidade"]:
                i["quantidade"] -= quantidade_produto

                print(f"Quantidade restante: {i['quantidade']}")

                organizar_vendas = {
                    "nome": produto_comprado,
                    "quantidade": quantidade_produto,
                    "valor da venda": i["preco"] * quantidade_produto
                }

                vendas.append(organizar_vendas)

                print("Venda realizada com sucesso!")

            else:
                print("Quantidade insuficiente!")

    if produto_encontrado == False:
        print("Produto não encontrado!")


def calcular_faturamento(vendas):
    soma = 0

    for i in vendas:
        soma += i["valor da venda"]

    return soma


def gerar_relatorio():
    quantidade_vendas = len(vendas)
    faturamento = calcular_faturamento(vendas)

    print("---- RELATÓRIO DE VENDAS ----")
    print("Quantidade de vendas:", quantidade_vendas)
    print(f"Faturamento: R$ {faturamento:.2f}")


def calcular_desconto(valor):
    desconto = 0

    if valor < 100:
        desconto = 0
    elif valor >= 100 and valor <= 299.99:
        desconto = 0.05
    elif valor >= 300:
        desconto = 0.1

    valor_final = valor - (valor * desconto)

    return valor_final


def contagem_regressiva(n):

    if n < 0:
        print("Número inválido!")

    elif n == 0:
        print(0)

    else:
        print(n)
        contagem_regressiva(n - 1)


